<!-- Source of truth: docs/privacy-notice.md (approved 20 Nov 2026). -->
<ul class="list-disc space-y-2 pl-5">
	<li>The app uses your <strong>MacBook's built-in camera</strong> to take photos of you from the front, sides and back, plus a few face close-ups.</li>
	<li>The camera is <strong>only on during the scan</strong> and turns off when you finish or leave.</li>
	<li>
		Photos stay in this browser until you click <strong>Generate 3D Model</strong>. Then they are saved <strong>only on this MacBook</strong>,
		encrypted, and used to build your 3D model.
	</li>
	<li>Nothing is sent to the internet or any cloud service.</li>
	<li>
		The 3D model is an <strong>approximation</strong> of you. We don't reshape your body or replace you with an avatar. If a good model can't be
		built, you'll see why.
	</li>
	<li>The try-on is a <strong>visual preview only</strong>, not your size or fit.</li>
	<li><strong>Discard scan & model</strong> deletes the photos and the model at any time.</li>
	<li>Turn <strong>off</strong> macOS video effects (Control Center → Video Effects) for a true-to-life scan.</li>
</ul>
